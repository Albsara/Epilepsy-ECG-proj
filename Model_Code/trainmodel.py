# ==========================================
# (A) Load the data and split it
# ==========================================
excel_path = "synthetic_seizure_dataset_20k.xlsx"
df = pd.read_excel(excel_path, sheet_name="encoded")

# Check that all required columns exist to avoid training errors
expected_cols = ["HR", "HRV", "Medication", "Symptoms", "Sleep", "Stress", "risk"]
missing = [c for c in expected_cols if c not in df.columns]

