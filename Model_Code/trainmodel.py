# ------------------------------------------
# 2. Professional confusion matrix plot
# ------------------------------------------
def plot_confusion_matrix_professional(y_true, y_pred, title):
    cm = confusion_matrix(y_true, y_pred)
    cm_percent = cm / cm.sum(axis=1, keepdims=True) * 100

    fig, ax = plt.subplots(figsize=(7, 6))

    image = ax.imshow(cm_percent, interpolation="nearest", cmap="Blues")

    cbar = fig.colorbar(image, ax=ax)
    cbar.set_label("Percentage within True Class", rotation=270, labelpad=18)

    ax.set_title(title, fontsize=15, fontweight="bold", pad=14)
    ax.set_xlabel("Predicted Label", fontsize=12, labelpad=10)
    ax.set_ylabel("True Label", fontsize=12, labelpad=10)

    ax.set_xticks(np.arange(len(class_names)))
    ax.set_yticks(np.arange(len(class_names)))
    ax.set_xticklabels(class_names, fontsize=11)
    ax.set_yticklabels(class_names, fontsize=11)

    threshold = cm_percent.max() / 2

    for i in range(cm.shape[0]):
        for j in range(cm.shape[1]):
            text_color = "white" if cm_percent[i, j] > threshold else "black"
            ax.text(
                j,
                i,
                f"{cm[i, j]}\n({cm_percent[i, j]:.1f}%)",
                ha="center",
                va="center",
                color=text_color,
                fontsize=12,
                fontweight="bold"
            )

    ax.set_ylim(len(class_names) - 0.5, -0.5)

    for spine in ax.spines.values():
        spine.set_visible(False)

    ax.set_xticks(np.arange(len(class_names) + 1) - 0.5, minor=True)
    ax.set_yticks(np.arange(len(class_names) + 1) - 0.5, minor=True)
    ax.grid(which="minor", color="white", linestyle="-", linewidth=2)
    ax.tick_params(which="minor", bottom=False, left=False)

    plt.tight_layout()
    plt.show()

    return cm


# ------------------------------------------
# 3. Evaluation function
# ------------------------------------------
def evaluate_random_forest(split_name, y_true, y_pred, y_prob):
    print("\n" + "=" * 55)
    print(f"Random Forest Evaluation on {split_name} Set")
    print("=" * 55)

    accuracy = accuracy_score(y_true, y_pred)
    precision = precision_score(y_true, y_pred, average="weighted", zero_division=0)
    recall = recall_score(y_true, y_pred, average="weighted", zero_division=0)
    f1 = f1_score(y_true, y_pred, average="weighted", zero_division=0)

    print(f"Accuracy : {accuracy:.4f}")
    print(f"Precision: {precision:.4f}")
    print(f"Recall   : {recall:.4f}")
    print(f"F1-score : {f1:.4f}")

    try:
        auc = roc_auc_score(y_true, y_prob)
        print(f"ROC-AUC  : {auc:.4f}")
    except ValueError:
        print("ROC-AUC  : Not available")

    print("\nClassification Report:")
    print(classification_report(
        y_true,
        y_pred,
        target_names=class_names,
        zero_division=0
    ))

    cm = plot_confusion_matrix_professional(
        y_true,
        y_pred,
        f"Random Forest Confusion Matrix - {split_name} Set"
    )

    print("Confusion Matrix:")
    print(cm)

    return {
        "accuracy": accuracy,
        "precision": precision,
        "recall": recall,
        "f1_score": f1,
        "roc_auc": auc if "auc" in locals() else None,
        "confusion_matrix": cm
    }


