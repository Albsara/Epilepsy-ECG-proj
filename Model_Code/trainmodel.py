import matplotlib.pyplot as plt

from sklearn.metrics import (
    accuracy_score,
    precision_score,
    recall_score,
    f1_score,
    confusion_matrix,
    classification_report,
    roc_auc_score,
    roc_curve
)

class_names = ["Low Risk", "High Risk"]
feature_names = ["HR", "HRV", "Medication", "Symptoms", "Sleep", "Stress"]


